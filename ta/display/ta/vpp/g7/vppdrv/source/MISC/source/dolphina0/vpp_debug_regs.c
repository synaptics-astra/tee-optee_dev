UINT32 VPP_DEBUG_GetDumpSize(VPP_LOG_REG_DUMP_TYPE table_type)
{
    UINT32 size;

    switch(table_type)
    {
        case VPP_LOG_REG:
            size = sizeof(vpp_reg_table);
        break;
        case VPP_LOG_MP_REG:
            size = sizeof(vpp_mp_reg_table);
        break;
        case VPP_LOG_GFX_VOP_REG:
            size = sizeof(vpp_gfx_vop_reg_table);
        break;
        case VPP_LOG_HDRX_PIPE_REG:
            size = sizeof(vpp_hdrx_pipe_reg_table);
        break;
        case VPP_LOG_MTR_REG:
            size = sizeof(mtr_reg_table);
        break;
        default:
            size = 0;
    }
    return size;
}
