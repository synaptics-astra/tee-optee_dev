/**
 * Copy NSKAlgTable to ie_CryptoAlgNSKValTable[64] in SIE_SecureCtx
*/
int TSPTA_InitNSKAlgTable(void* secureContext) {
    uint32_t i = 0;
    SIE_SecureCtx *pSecureCtx = (SIE_SecureCtx *)secureContext;
    SIE_CryptoAlgorithmElement *pSrcNSK = NULL, *pSrcFigo = NULL, *pDestNSK = NULL, *pDestFigo = NULL;

    //make sure NSK_ALG_TABLE_USED_SIZE <= arr_SecureCtx_CryptoAlgNSKValTable
#if NSK_ALG_TABLE_USED_SIZE > arr_SecureCtx_CryptoAlgNSKValTable
#error NSK_ALG_TABLE_USED_SIZE shall not be larger than arr_SecureCtx_CryptoAlgNSKValTable
#endif

    pDestNSK = (SIE_CryptoAlgorithmElement *)&(pSecureCtx->ie_CryptoAlgNSKValTable);
    pDestFigo = (SIE_CryptoAlgorithmElement *)&(pSecureCtx->ie_CryptoAlgFigoValTable);
    pSrcNSK = (SIE_CryptoAlgorithmElement *)&NSKAlgNSKValTable;
    pSrcFigo= (SIE_CryptoAlgorithmElement *)&NSKAlgFigoValTable;

    TA_LOGH("%s: NSK Dest %p, Src %p; Figo Dest %p, Src %p items %d\n",
        __FUNCTION__, pDestNSK, pSrcNSK, pDestFigo, pSrcFigo, NSK_ALG_TABLE_USED_SIZE);

    for(; i < NSK_ALG_TABLE_USED_SIZE; i++) {
        memcpy(pDestNSK, pSrcNSK, sizeof(SIE_CryptoAlgorithmElement));
        memcpy(pDestFigo, pSrcFigo, sizeof(SIE_CryptoAlgorithmElement));
        TA_LOGI("%s: Index %2d: 0x%x -> 0x%x, : 0x%x -> 0x%x\n", __FUNCTION__, i,
            *(uint32_t*)(pSrcNSK), *(uint32_t*)(pDestNSK),
            *(uint32_t*)(pSrcFigo), *(uint32_t*)(pDestFigo));
        pDestNSK++;
        pSrcNSK++;
        pDestFigo++;
        pSrcFigo++;
    }

    TA_LOGH("%s:%d, update algTable ok\n", __FUNCTION__, __LINE__);
    return TEE_SUCCESS;
}

bool TSPTA_shallAllocateFixedZeroIV(uint32_t algId) {
    if (algId >= NSA_DSS_MDI_MSC4) {
        algId -= (NSK_ALG_TS_OFFSET + NSK_ALG_TS_DIRECTV_OFFSET);
    } else if (algId >= DVB_CSA2) {
        algId -= NSK_ALG_TS_OFFSET;
    }
    if(algId <= NSK_ALG_TABLE_USED_SIZE)
        return ((NSKAlgNSKValTable[algId].u_IV == CryptoAlgorithmElement_IV_ClearIV_with_fixed_value ||
                NSKAlgNSKValTable[algId].u_IV == CryptoAlgorithmElement_IV_IV_calculated_by_MDI ||
                NSKAlgNSKValTable[algId].u_IV == CryptoAlgorithmElement_IV_IV_calculated_by_MDD) ? true : false);
    return false;
}
